-- =====================================================================
-- Gastos - UNO · Presupuestos por categoría
-- Se ejecuta UNA sola vez en Supabase > SQL Editor > New query > Run.
-- Crea UNA tabla nueva (presupuestos). No modifica ni borra datos de
-- usuarios, categorias, cuenta ni movimientos.
-- =====================================================================

create table if not exists public.presupuestos (
  id           bigint generated by default as identity primary key,
  idusuario    bigint not null references public.usuarios(id)   on delete cascade,
  idcategoria  bigint not null references public.categorias(id) on delete cascade,
  monto        numeric(14,2) not null check (monto > 0),
  created_at   timestamptz not null default now(),
  unique (idusuario, idcategoria)   -- un solo límite por categoría
);

-- Seguridad: cada persona solo ve y modifica SUS presupuestos.
alter table public.presupuestos enable row level security;

do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename  = 'presupuestos'
      and policyname = 'presupuestos_del_usuario'
  ) then
    create policy "presupuestos_del_usuario" on public.presupuestos
      for all to authenticated
      using (
        idusuario in (
          select u.id from public.usuarios u
          where u.idauth_supabase::text = auth.uid()::text
        )
      )
      with check (
        idusuario in (
          select u.id from public.usuarios u
          where u.idauth_supabase::text = auth.uid()::text
        )
      );
  end if;
end $$;

-- Avisa a la API que hay una tabla nueva.
notify pgrst, 'reload schema';

